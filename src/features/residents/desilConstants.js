export const DESIL_MAP = Object.fromEntries(
  DESIL_OPTIONS.map((opt) => [opt.value, opt])
)

export function getDesilMeta(desil) {
  const d = Number(desil) || 1
  return (
    DESIL_MAP[d] || {
      value: d,
      label: `Desil ${d}`,
      selectLabel: `Desil ${d}`,
      shortLabel: `Desil ${d}`,
      category: d <= 4 ? 'Prioritas' : 'Non-Prioritas',
      bg: '#f1f5f9',
      color: '#475569',
      border: '#cbd5e1',
      dtksStatus: d <= 4 ? 'TERDAFTAR' : 'BELUM_TERDAFTAR',
      socialAidEligibility:
        d <= 2
          ? 'PRIORITAS_UTAMA'
          : d === 3
          ? 'PRIORITAS_SEDANG'
          : d === 4
          ? 'CADANGAN'
          : 'TIDAK_LAYAK',
      povertyIndex: Math.max(5, 100 - d * 10),
      priorityTag: d <= 4 ? 'Prioritas Bansos' : 'Non-Bansos',
    }
  )
}

